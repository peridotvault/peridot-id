/// Process a Peridot smart-account instruction.
///
/// # Safety
/// The entrypoint is generated by the `entrypoint!` macro; the unsafe deserialization is
/// contained there.
pub fn process_instruction(
    program_id: &Address,
    accounts: &[AccountView],
    instruction_data: &[u8],
) -> ProgramResult {
    if program_id != &ID {
        return Err(ProgramError::IncorrectProgramId);
    }

    let (discriminator, data) = instruction_data
        .split_first()
        .ok_or(ProgramError::InvalidInstructionData)?;
    let instruction_data = InstructionData::new(data)?;

    match Instruction::try_from(*discriminator)? {
            Instruction::Initialize => instructions::initialize::process(program_id, accounts, &instruction_data),
            Instruction::WithdrawSol => instructions::withdraw_sol::process(program_id, accounts, &instruction_data),
            Instruction::WithdrawToken => instructions::withdraw_token::process(program_id, accounts, &instruction_data),
            Instruction::UpdateAuthority => instructions::update_authority::process(program_id, accounts, &instruction_data),
            Instruction::Close => instructions::close::process(program_id, accounts, &instruction_data),
            Instruction::Activate => instructions::activate::process(program_id, accounts, &instruction_data),
            Instruction::Execute => instructions::execute::process(program_id, accounts, &instruction_data),
            Instruction::RegisterSession => instructions::register_session::process(program_id, accounts, &instruction_data),
            Instruction::SessionExecute => instructions::session_execute::process(program_id, accounts, &instruction_data),
            Instruction::RevokeSession => instructions::revoke_session::process(program_id, accounts, &instruction_data),
            Instruction::CloseSession => instructions::close_session::process(program_id, accounts, &instruction_data),
            Instruction::WithdrawSolV4 => instructions::withdraw_sol_v4::process(program_id, accounts, &instruction_data),
            Instruction::WithdrawTokenV4 => instructions::withdraw_token_v4::process(program_id, accounts, &instruction_data),
            Instruction::ExecuteV4 => instructions::execute_v4::process(program_id, accounts, &instruction_data),
            Instruction::ActivateV4 => instructions::activate_v4::process(program_id, accounts, &instruction_data),
            Instruction::InitTreasury => instructions::init_treasury::process(program_id, accounts, &instruction_data),
            Instruction::WithdrawRevenue => instructions::withdraw_revenue::process(program_id, accounts, &instruction_data),
            Instruction::AddAdmin => instructions::add_admin::process(program_id, accounts, &instruction_data),
            Instruction::RemoveAdmin => instructions::remove_admin::process(program_id, accounts, &instruction_data),
        }
}

#[cfg(test)]
fn assert_effect_before_interaction(file: &str, src: &str, effect: &str, interaction: &str) {
    let e = src
        .find(effect)
        .unwrap_or_else(|| panic!("{file}: expected `{effect}` not found"));
    let i = src
        .find(interaction)
        .unwrap_or_else(|| panic!("{file}: expected `{interaction}` not found"));
    assert!(
        e < i,
        "{file}: `{effect}` (byte {e}) must precede `{interaction}` (byte {i})"
    );
}

/// ANT-16 (child of ANT-12) hardening regression: effects-before-interactions.
/// Every spend path must burn its nonce / consume its sequence number BEFORE
/// any untrusted CPI or value movement. A failed CPI reverts atomically, so
/// the reorder is behavior-preserving; the value is audit cleanliness plus
/// reentrancy defense-in-depth (a reentrant second call with the same
/// signature/seq observes spent state and fails).
#[cfg(test)]
mod ant16_ordering_tests {
    use super::assert_effect_before_interaction;

    #[test]
    fn execute_burns_nonce_before_cpi() {
        assert_effect_before_interaction(
            "execute.rs",
            include_str!("instructions/execute.rs"),
            "increment_nonce()",
            "invoke_signed_with_slice",
        );
    }

    #[test]
    fn withdraw_token_burns_nonce_before_cpi() {
        assert_effect_before_interaction(
            "withdraw_token.rs",
            include_str!("instructions/withdraw_token.rs"),
            "increment_nonce()",
            "invoke_signed",
        );
    }

    #[test]
    fn withdraw_sol_burns_nonce_before_value_moves() {
        assert_effect_before_interaction(
            "withdraw_sol.rs",
            include_str!("instructions/withdraw_sol.rs"),
            "increment_nonce()",
            "set_lamports",
        );
    }

    #[test]
    fn session_execute_consumes_seq_before_cpi() {
        assert_effect_before_interaction(
            "session_execute.rs",
            include_str!("instructions/session_execute.rs"),
            ".advance(",
            "invoke_signed_with_slice",
        );
    }

    #[test]
    fn register_session_burns_nonce_before_create_cpi() {
        assert_effect_before_interaction(
            "register_session.rs",
            include_str!("instructions/register_session.rs"),
            "increment_nonce()",
            "invoke_signed",
        );
    }

    #[test]
    fn close_session_burns_nonce_before_value_moves() {
        assert_effect_before_interaction(
            "close_session.rs",
            include_str!("instructions/close_session.rs"),
            "increment_nonce()",
            "set_lamports",
        );
    }

    #[test]
    fn session_execute_snapshots_after_seq_advance() {
        // F1 (ANT-30): the protected-accounts snapshot must be taken AFTER
        // the `advance`/`record_seen` write. Both mutate the session record
        // bytes (see `advance_and_record_seen_mutate_record_bytes` in
        // state.rs), so a pre-advance snapshot of a protected session PDA
        // (rent-pinning) would never match post-CPI state and every such
        // call would revert with `SessionScopeViolation` (0x15).
        let src = include_str!("instructions/session_execute.rs");
        assert_effect_before_interaction("session_execute.rs", src, ".advance(", "let mut snapshots");
        assert_effect_before_interaction(
            "session_execute.rs",
            src,
            "record_seen(",
            "let mut snapshots",
        );
    }
}

/// ANT-211 regression: the program ID is build-configurable (`PID_PROGRAM_ID`
/// consumed by `build.rs`, default local/devnet `CiwLJ…`), not hardcoded.
/// These tests are env-agnostic — they pin the *binding*, not the value — so
/// they pass identically for default and testnet (`D6TpM7…`) builds.
#[cfg(test)]
mod ant211_program_id_tests {
    use super::{check_id, id, process_instruction, ID};
    use pinocchio::error::ProgramError;

    #[test]
    fn built_id_is_self_consistent() {
        // Same shape `declare_id!` used to provide: `ID`, `id()`, `check_id`.
        assert!(check_id(&ID));
        assert!(check_id(&id()));
        assert_eq!(id(), ID);
    }

    #[test]
    fn entrypoint_rejects_foreign_program_id() {
        // Any `program_id` other than the baked `ID` fails closed before any
        // account or instruction-data access.
        let mut raw = *ID.as_array();
        raw[0] ^= 0xff;
        let foreign = pinocchio::Address::new_from_array(raw);
        assert_ne!(foreign, ID);
        let err = process_instruction(&foreign, &[], &[0u8]).unwrap_err();
        assert_eq!(err, ProgramError::IncorrectProgramId);
    }

    #[test]
    fn entrypoint_accepts_built_id_past_gate() {
        // With the baked `ID`, the gate passes and execution reaches argument
        // parsing (empty data → `InvalidInstructionData`, not `IncorrectProgramId`).
        // Proves a clean-source build executes under whatever ID it was built with.
        let err = process_instruction(&ID, &[], &[]).unwrap_err();
        assert_eq!(err, ProgramError::InvalidInstructionData);
    }
}

/// ANT-16(e) (child of ANT-12) hardening regression: direct `initialize` is
/// deprecated (ANT-22 Option A) — creation must route through `activate`, the
/// sole fee-bearing sponsored-creation path. Testnet/devnet builds keep
/// `initialize` functional plus a deprecation event; production builds reject
/// via `check_initialize_allowed` before any other validation.
#[cfg(test)]
mod ant16e_deprecation_tests {
    use super::assert_effect_before_interaction;

    #[test]
    fn initialize_gate_runs_before_creation_cpi() {
        // t-e1 mechanism pin: the production gate must precede the PDA
        // creation CPI, so no fee-free account can be minted where `activate`
        // (and its 50% sponsored-creation fee) was due. The `true` arm itself
        // is a two-line pure function (`check_initialize_allowed`); behavior
        // on a production build is covered by the session.mjs/integration
        // creation suites in CI (validator-gated, not host-runnable).
        assert_effect_before_interaction(
            "initialize.rs",
            include_str!("instructions/initialize.rs"),
            "check_initialize_allowed()",
            "    create_account_with_minimum_balance_signed(",
        );
    }

    #[test]
    fn initialize_deprecated_error_is_additive() {
        // t-e1 discriminant pin: additive-only error enum — existing
        // discriminants are untouched so old SDK decoders keep working.
        let src = include_str!("errors.rs");
        assert!(
            src.contains("InitializeDeprecated = 23"),
            "errors.rs: expected `InitializeDeprecated = 23`"
        );
    }

    #[test]
    fn initialize_emits_deprecation_event() {
        // t-e2 pin: testnet/devnet `initialize` succeeds exactly as before
        // PLUS the deprecation event for drift alerting (ANT-16(c) sink).
        let src = include_str!("instructions/initialize.rs");
        assert!(
            src.contains("PeridotEvent::AccountInitialized"),
            "initialize.rs: success event missing"
        );
        assert!(
            src.contains("PeridotEvent::AccountInitializeDeprecated"),
            "initialize.rs: deprecation event missing"
        );
    }

    #[test]
    fn testnet_gate_is_open() {
        // This build is the testnet/devnet build: `initialize` stays
        // functional. Production flips the const (ANT-22 Q1, owner: CTO).
        assert!(
            !crate::instructions::initialize::DEPRECATE_DIRECT_INITIALIZE,
            "testnet build must keep direct initialize functional"
        );
        assert!(crate::instructions::initialize::check_initialize_allowed().is_ok());
    }
}

/// ANT-635 revenue vault regression (ANT-638): additive-only pins.
/// New instructions take discriminants 15-18 (spec ANT-637 reserved 11-14,
/// but those were already taken by the V4 siblings); new errors take 25-28
/// (spec error 24 collided with `SessionSpendExceeded`). Existing 0-14 and
/// 0-24 are frozen so old SDK decoders keep working.
#[cfg(test)]
mod ant635_vault_pins {
    use crate::errors::PeridotError;
    use crate::instructions::Instruction;

    #[test]
    fn existing_instruction_discriminants_frozen() {
        assert_eq!(Instruction::Initialize as u8, 0);
        assert_eq!(Instruction::WithdrawSol as u8, 1);
        assert_eq!(Instruction::WithdrawToken as u8, 2);
        assert_eq!(Instruction::UpdateAuthority as u8, 3);
        assert_eq!(Instruction::Close as u8, 4);
        assert_eq!(Instruction::Activate as u8, 5);
        assert_eq!(Instruction::Execute as u8, 6);
        assert_eq!(Instruction::RegisterSession as u8, 7);
        assert_eq!(Instruction::SessionExecute as u8, 8);
        assert_eq!(Instruction::RevokeSession as u8, 9);
        assert_eq!(Instruction::CloseSession as u8, 10);
        assert_eq!(Instruction::WithdrawSolV4 as u8, 11);
        assert_eq!(Instruction::WithdrawTokenV4 as u8, 12);
        assert_eq!(Instruction::ExecuteV4 as u8, 13);
        assert_eq!(Instruction::ActivateV4 as u8, 14);
    }

    #[test]
    fn vault_instruction_discriminants_pinned() {
        assert_eq!(Instruction::InitTreasury as u8, 15);
        assert_eq!(Instruction::WithdrawRevenue as u8, 16);
        assert_eq!(Instruction::AddAdmin as u8, 17);
        assert_eq!(Instruction::RemoveAdmin as u8, 18);
        assert_eq!(Instruction::try_from(15u8).unwrap(), Instruction::InitTreasury);
        assert_eq!(Instruction::try_from(16u8).unwrap(), Instruction::WithdrawRevenue);
        assert_eq!(Instruction::try_from(17u8).unwrap(), Instruction::AddAdmin);
        assert_eq!(Instruction::try_from(18u8).unwrap(), Instruction::RemoveAdmin);
        assert!(Instruction::try_from(19u8).is_err());
    }

    #[test]
    fn vault_errors_pinned_additive() {
        // New vault errors (spec 24-27 shifted to 25-28: 24 was taken).
        assert_eq!(PeridotError::NotAdmin as u32, 25);
        assert_eq!(PeridotError::ConfigAlreadyInitialized as u32, 26);
        assert_eq!(PeridotError::TooManyAdmins as u32, 27);
        assert_eq!(PeridotError::CannotRemoveLastAdmin as u32, 28);
        // Pre-existing errors frozen.
        assert_eq!(PeridotError::AlreadyInitialized as u32, 0);
        assert_eq!(PeridotError::Forbidden as u32, 11);
        assert_eq!(PeridotError::InitializeDeprecated as u32, 23);
        assert_eq!(PeridotError::SessionSpendExceeded as u32, 24);
    }

    #[test]
    fn fee_paths_verify_pda_vault_not_const() {
        // D5 pin: no fee call-site may reference the removed treasury const
        // in code (comments may still name it for migration notes).
        for (file, src) in [
            ("activate.rs", include_str!("instructions/activate.rs")),
            ("activate_v4.rs", include_str!("instructions/activate_v4.rs")),
            ("withdraw_sol.rs", include_str!("instructions/withdraw_sol.rs")),
            ("withdraw_sol_v4.rs", include_str!("instructions/withdraw_sol_v4.rs")),
            ("withdraw_token.rs", include_str!("instructions/withdraw_token.rs")),
            (
                "withdraw_token_v4.rs",
                include_str!("instructions/withdraw_token_v4.rs"),
            ),
            ("execute.rs", include_str!("instructions/execute.rs")),
            ("execute_v4.rs", include_str!("instructions/execute_v4.rs")),
        ] {
            assert!(
                src.contains("verify_treasury_pda(treasury, program_id)?"),
                "{file}: must verify the [b\"treasury\"] PDA"
            );
            assert!(
                !src.contains("&TREASURY"),
                "{file}: must not reference the removed const in code"
            );
        }
    }

    #[test]
    fn vault_emits_additive_events() {
        assert!(include_str!("instructions/init_treasury.rs")
            .contains("PeridotEvent::TreasuryInitialized"));
        assert!(include_str!("instructions/withdraw_revenue.rs")
            .contains("PeridotEvent::RevenueWithdrawn"));
        assert!(include_str!("instructions/add_admin.rs").contains("PeridotEvent::AdminAdded"));
        assert!(include_str!("instructions/remove_admin.rs")
            .contains("PeridotEvent::AdminRemoved"));
    }

    #[test]
    fn vault_never_touches_user_or_session_state() {
        // D1/D3 pin: vault instructions must not reference user/session state
        // or the backend allowlist as code (deny-comments may still name them
        // for audit traceability — only code references count).
        for (file, src) in [
            (
                "init_treasury.rs",
                include_str!("instructions/init_treasury.rs"),
            ),
            (
                "withdraw_revenue.rs",
                include_str!("instructions/withdraw_revenue.rs"),
            ),
            ("add_admin.rs", include_str!("instructions/add_admin.rs")),
            (
                "remove_admin.rs",
                include_str!("instructions/remove_admin.rs"),
            ),
        ] {
            for needle in [
                "SmartAccount",
                "SessionAccount",
                "BACKEND",
                "verify_secp256r1",
            ] {
                let code_hits = src
                    .lines()
                    .filter(|l| {
                        let t = l.trim_start();
                        !(t.starts_with("//") || t.starts_with("//!") || t.starts_with('*'))
                            && l.contains(needle)
                    })
                    .collect::<alloc::vec::Vec<_>>();
                assert!(
                    code_hits.is_empty(),
                    "{file}: must not reference `{needle}` in code (D1/D3)"
                );
            }
            // D4 pin: WithdrawRevenue performs NO CPI / NO invoke_signed
            // (direct set_lamports only); the deny-comment names it.
            // InitTreasury DOES invoke_signed in code (system create_account
            // with PDA seeds) — that is its only CPI and it is expected.
            if file == "withdraw_revenue.rs" {
                let hits = src
                    .lines()
                    .filter(|l| l.contains("invoke_signed"))
                    .collect::<alloc::vec::Vec<_>>();
                assert!(
                    hits.iter().all(|l| l.trim_start().starts_with("//")),
                    "{file}: invoke_signed must appear in comments only (D4)"
                );
            }
        }
    }
}
